OFF_TOPIC_KEYWORDS = [
    # ألعاب
    "ببجي", "pubg", "فورتنايت", "fortnite", "ماينكرافت", "minecraft",
    "فيفا", "fifa", "بلايستيشن", "playstation", "ألعاب", "لعبة",
    # رياضة
    "ماتش", "كورة", "الأهلي", "الزمالك", "ريال مدريد", "برشلونة",
    # سياسة
    "سياسة", "رئيس", "حكومة", "انتخابات", "ثورة",
    # دين
    "فتوى", "حلال", "حرام", "دين", "صلاة", "قرآن",
    # ترفيه
    "أغنية", "مطرب", "فيلم", "مسلسل", "مشاهدة",
    # برمجة
    "برمجة", "كود", "python", "javascript", "برنامج",
    # عام
    "الجو", "طقس", "سيارة", "عقار", "شغل", "وظيفة",
]

OFF_TOPIC_RESPONSE = (
    "🙋 أنا مساعد صيدلية *H1-AI*، متخصص في:\n\n"
    "💊 الأدوية والتفاعلات\n"
    "🩺 الأعراض الصحية\n"
    "📦 توفير المنتجات\n"
    "🛒 الطلبات\n\n"
    "مش هقدر أساعد في مواضيع تانية — لكن لو عندك أي سؤال صحي، أنا هنا ✋"
)


def check_off_topic(message: str) -> str | None:
    """يرجع رد إذا كانت الرسالة خارج الموضوع."""
    msg_lower = message.lower()

    # ⚠️ استثناءات — لا نريد منعها
    exceptions = [
        "أكل", "طعام", "دايت", "رجيم", "وزن", "تخسيس",
        "رياضة", "تمرين", "مشي", "جيم",
        "نوم", "أرق",
    ]
    if any(exc in msg_lower for exc in exceptions):
        return None

    for kw in OFF_TOPIC_KEYWORDS:
        if kw in msg_lower:
            return OFF_TOPIC_RESPONSE

    return None
