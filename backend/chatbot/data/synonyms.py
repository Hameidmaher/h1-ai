def expand_synonyms(term: str) -> List[str]:
    """وسّع المصطلح لكل المرادفات."""
    term_lower = term.lower().strip()
    for key, values in DRUG_SYNONYMS.items():
        if term_lower in [v.lower() for v in values] or term_lower == key:
            return [key] + values
    for key, values in SYMPTOM_SYNONYMS.items():
        if term_lower in [v.lower() for v in values] or term_lower == key:
            return [key] + values
    return [term]

def find_symptom_key(term: str) -> str | None:
    """حوّل عرض لمفتاحه القياسي."""
    term_lower = term.lower().strip()
    for key, values in SYMPTOM_SYNONYMS.items():
        if term_lower == key or term_lower in [v.lower() for v in values]:
            return key
    return None

def find_symptom_terms(symptom: str) -> List[str]:
    """رجّع كل المرادفات لعرض."""
    key = find_symptom_key(symptom)
    if not key:
        return [symptom]
    return SYMPTOM_SYNONYMS.get(key, [symptom])
