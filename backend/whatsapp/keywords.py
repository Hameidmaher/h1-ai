def normalize_text(text: str) -> str:
    """تطبيع بسيط للنص."""
    if not text:
        return ""
    text = text.lower()
    # توحيد الألف
    text = text.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    # توحيد الياء
    text = text.replace("ى", "ي")
    # توحيد التاء المربوطة
    text = text.replace("ة", "ه")
    return text
